// Spec: knowledge/components/adyen-agentic-commerce.md
// Builds the MCP Apps widget script and collects the plugin's files into one generated module,
// because the standalone server ships no source files to read at run time.
// Run: bun run widgets (after any change under src/widgets or plugin/atelier-velune).
import { readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { APP, PLUGIN_DIR, pluginFiles, sourceHash, WIDGETS_DIR } from "./widget-sources";

const built = await Bun.build({
  entrypoints: [join(WIDGETS_DIR, "app.ts")],
  target: "browser",
  format: "iife",
  minify: true,
});
if (!built.success || built.outputs.length !== 1) {
  for (const log of built.logs) console.error(log);
  throw new Error("The widget bundle did not build");
}
const script = await built.outputs[0]!.text();
const css = readFileSync(join(WIDGETS_DIR, "widget.css"), "utf8");
const plugin = Object.fromEntries(
  pluginFiles().map((path) => [relative(PLUGIN_DIR, path), readFileSync(path, "utf8")]),
);

const out = join(APP, "src/server/mcp/widgets.gen.ts");
writeFileSync(
  out,
  [
    "// Generated by scripts/build-widgets.ts from src/widgets and plugin/atelier-velune: do not edit.",
    "// Spec: knowledge/components/adyen-agentic-commerce.md",
    `export const SOURCE_HASH = ${JSON.stringify(sourceHash())};`,
    `export const WIDGET_SCRIPT = ${JSON.stringify(script)};`,
    `export const WIDGET_CSS = ${JSON.stringify(css)};`,
    `export const PLUGIN_FILES: Record<string, string> = ${JSON.stringify(plugin, null, 2)};`,
    "",
  ].join("\n"),
);
console.log(
  `${relative(APP, out)}: script ${script.length} B, ${Object.keys(plugin).length} plugin files`,
);
